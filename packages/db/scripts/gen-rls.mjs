#!/usr/bin/env node
// Emits the row level security migration SQL for the current Drizzle schema.
//
// Source of truth: the latest drizzle-kit snapshot in packages/db/migrations/meta
// (the snapshot mirrors packages/db/src/schema exactly after `pnpm db:generate`).
// Every public table with a `tenant_id` column gets ENABLE + FORCE row level
// security and `tenant_isolation_policy`; `tenants` is scoped by its own `id`.
//
// Usage: node packages/db/scripts/gen-rls.mjs > /tmp/rls.sql
// Review the output, then paste it into a `drizzle-kit generate --custom` file.
//
// For a table added after 0002_rls: `node packages/db/scripts/gen-rls.mjs --tables a,b`
// prints only those tables' statements (they must have a `tenant_id` column),
// for the custom migration that follows the one creating them.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MIGRATIONS_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../migrations');
const BREAK = '--> statement-breakpoint';

function latestSnapshot() {
  const journal = JSON.parse(fs.readFileSync(path.join(MIGRATIONS_DIR, 'meta/_journal.json'), 'utf8'));
  const last = journal.entries.at(-1);
  if (!last) throw new Error('migrations journal is empty; run drizzle-kit generate first');
  const idx = String(last.idx).padStart(4, '0');
  return JSON.parse(fs.readFileSync(path.join(MIGRATIONS_DIR, `meta/${idx}_snapshot.json`), 'utf8'));
}

const ident = (name) => {
  if (!/^[a-z_][a-z0-9_]*$/.test(name)) throw new Error(`unexpected table name: ${name}`);
  return name;
};

const snapshot = latestSnapshot();
const tables = Object.values(snapshot.tables)
  .filter((t) => (t.schema || 'public') === 'public')
  .sort((a, b) => a.name.localeCompare(b.name));

const tenantTables = tables.filter((t) => Object.hasOwn(t.columns, 'tenant_id')).map((t) => ident(t.name));
if (!tables.some((t) => t.name === 'tenants')) throw new Error('schema has no tenants table');

function tenantPolicy(table) {
  return [
    `ALTER TABLE public.${table} ENABLE ROW LEVEL SECURITY;`,
    `ALTER TABLE public.${table} FORCE ROW LEVEL SECURITY;`,
    `CREATE POLICY tenant_isolation_policy ON public.${table}
  USING (tenant_id = public.current_tenant_id())
  WITH CHECK (tenant_id = public.current_tenant_id());`,
  ];
}

const tablesArg = process.argv.indexOf('--tables');
if (tablesArg !== -1) {
  const wanted = (process.argv[tablesArg + 1] ?? '').split(',').filter(Boolean).map(ident);
  if (wanted.length === 0) throw new Error('--tables needs a comma-separated list of table names');
  const only = [];
  for (const table of wanted) {
    if (!tenantTables.includes(table)) throw new Error(`not a tenant table in the latest snapshot: ${table}`);
    only.push(...tenantPolicy(table));
  }
  process.stdout.write(
    `-- Generated by packages/db/scripts/gen-rls.mjs --tables ${wanted.join(',')}. Do not edit by hand.\n` +
      only.join(`\n${BREAK}\n`) +
      '\n'
  );
  process.exit(0);
}

const statements = [
  `-- Generated by packages/db/scripts/gen-rls.mjs. Do not edit by hand; regenerate and review.
-- Fails closed: an unset or empty app.tenant_id yields NULL, and NULL = x is never true.
CREATE OR REPLACE FUNCTION public.current_tenant_id() RETURNS uuid
LANGUAGE sql
STABLE
AS $$
  SELECT NULLIF(current_setting('app.tenant_id', true), '')::uuid;
$$;`,
];

for (const table of tenantTables) {
  statements.push(...tenantPolicy(table));
}

statements.push(
  `ALTER TABLE public.tenants ENABLE ROW LEVEL SECURITY;`,
  `ALTER TABLE public.tenants FORCE ROW LEVEL SECURITY;`,
  `CREATE POLICY tenant_self_policy ON public.tenants
  USING (id = public.current_tenant_id())
  WITH CHECK (id = public.current_tenant_id());`
);

process.stdout.write(statements.join(`\n${BREAK}\n`) + '\n');
